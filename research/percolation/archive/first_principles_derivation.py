import pandas as pd
df = pd.read_csv(f'{OUT}/complete_dataset_v4.csv')
z = df['z'].values.astype(float)
d = df['d'].values.astype(float)
g = df['g'].values.astype(float)
pc = df['pc'].values

# 理论预言的参数
gamma_theory = (d - 1) / d  # 对于每个数据点
alpha_theory = 1 / 6  # d_c = 6
z0_theory = 10.0

# 拟合 a 使得理论参数最优
def model_theory(a, z, d, g):
    gamma = (d - 1) / d
    alpha = 1 / 6
    z0 = 10.0
    correction = (a / g**gamma) * np.exp(-alpha * d) * (1 - np.exp(-z / z0))
    return (1 + correction) / (z - 1)

# 优化 a
best_a = None
best_ss = np.inf
for a in np.linspace(5, 30, 100):
    pred = model_theory(a, z, d, g)
    ss = np.sum((pc - pred)**2)
    if ss < best_ss:
        best_ss = ss
        best_a = a

pred_theory = model_theory(best_a, z, d, g)
errors_theory = np.abs((pc - pred_theory) / pc) * 100
mape_theory = np.mean(errors_theory)

print(f"\n理论预言模型 (γ=(d-1)/d, α=1/6, z₀=10):")
print(f"  最优 a = {best_a:.2f}")
print(f"  MAPE = {mape_theory:.2f}%")

# 经验拟合模型
def model_empirical(params, z, d, g):
    a, alpha, gamma, z0 = params
    correction = (a / g**gamma) * np.exp(-alpha * d) * (1 - np.exp(-z / z0))
    return (1 + correction) / (z - 1)

